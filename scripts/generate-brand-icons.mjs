#!/usr/bin/env node
/**
 * Regenerate xNet icons and PNG exports: node scripts/generate-brand-icons.mjs
 * Source artwork lives in site/public/mark.svg and site/public/wordmark.svg.
 * Uses the site's existing sharp dependency (pnpm --dir site install --ignore-workspace).
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'

const require = createRequire(new URL('../site/package.json', import.meta.url))
const sharp = require('sharp')
const file = (path) => new URL(`../${path}`, import.meta.url)
const source = await readFile(file('site/public/mark.svg'), 'utf8')
const body = source.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>\s*$/)?.[1].trim()
if (!body || !source.includes('viewBox="0 0 100 100"')) {
  throw new Error('Expected site/public/mark.svg to use a 100 × 100 viewBox')
}

const svg = (content, color = '#fff') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="currentColor" style="color:${color}">${content}</svg>`
const mark = (scale) =>
  `<g transform="translate(${(100 - scale * 100) / 2} ${(100 - scale * 100) / 2}) scale(${scale})">${body}</g>`
const tile = (radius, scale = 0.74) =>
  `<rect width="100" height="100" rx="${radius}" fill="#000"/>${mark(scale)}`
const artwork = {
  // iOS and web install surfaces apply their own corner masks.
  app: svg(tile(0)),
  desktop: svg(tile(23)),
  // Legacy ICNS files need their own tile and breathing room on older macOS.
  mac: svg(`<g transform="translate(6.25 6.25) scale(.875)">${tile(23)}</g>`),
  favicon: svg(tile(23, 0.84)),
  mask: svg(body),
  // Keep every arm inside Android's 66 dp safe circle in a 108 dp layer.
  // https://developer.android.com/develop/ui/compose/system/icon_design_adaptive
  adaptive: svg(mark(0.52))
}

const png = (kind, size, opaque = false) => {
  const rendered = sharp(Buffer.from(artwork[kind]), { density: (size / 100) * 72 }).resize(
    size,
    size
  )
  return (opaque ? rendered.removeAlpha() : rendered).png().toBuffer()
}

const rasterFiles = [
  ['apps/electron/build/icon.png', 'desktop', 1024],
  ['apps/expo/assets/icon.png', 'app', 1024, true],
  ['apps/expo/assets/adaptive-icon.png', 'adaptive', 1024],
  ['apps/web/public/apple-touch-icon.png', 'app', 180, true],
  ['apps/web/public/icons/icon-192.png', 'app', 192, true],
  ['apps/web/public/icons/icon-512.png', 'app', 512, true],
  ['site/public/mark.png', 'mask', 96]
]

// ICO stores a directory of PNG representations, including real small-size renders.
const ico = async (kind, sizes) => {
  const images = await Promise.all(sizes.map((size) => png(kind, size)))
  const header = Buffer.alloc(6)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  const entries = images.map((image, index) => {
    const entry = Buffer.alloc(16)
    entry[0] = entry[1] = sizes[index] === 256 ? 0 : sizes[index]
    entry.writeUInt16LE(1, 4)
    entry.writeUInt16LE(32, 6)
    entry.writeUInt32LE(image.length, 8)
    entry.writeUInt32LE(
      6 + images.length * 16 + images.slice(0, index).reduce((sum, item) => sum + item.length, 0),
      12
    )
    return entry
  })
  return Buffer.concat([header, ...entries, ...images])
}

// PNG-backed ICNS chunks keep generation portable; no macOS-only iconutil required.
const icns = async () => {
  const representations = [
    ['icp4', 16],
    ['icp5', 32],
    ['icp6', 64],
    ['ic07', 128],
    ['ic08', 256],
    ['ic09', 512],
    ['ic10', 1024],
    ['ic11', 32],
    ['ic12', 64],
    ['ic13', 256],
    ['ic14', 512]
  ]
  const chunks = await Promise.all(
    representations.map(async ([type, size]) => {
      const image = await png('mac', size)
      const header = Buffer.alloc(8)
      header.write(type, 0, 4, 'ascii')
      header.writeUInt32BE(image.length + 8, 4)
      return Buffer.concat([header, image])
    })
  )
  const header = Buffer.alloc(8)
  header.write('icns', 0, 4, 'ascii')
  header.writeUInt32BE(8 + chunks.reduce((sum, chunk) => sum + chunk.length, 0), 4)
  return Buffer.concat([header, ...chunks])
}

const favicon = `<!-- Generated by scripts/generate-brand-icons.mjs from mark.svg. -->
${artwork.favicon}
`

const wordmarkSource = await readFile(file('site/public/wordmark.svg'), 'utf8')
const brandSources = [
  ['mark', source, 2048],
  ['wordmark', wordmarkSource, 2400]
]
const brandExports = brandSources.flatMap(([name, artwork, width]) =>
  [
    ['black', '#000000'],
    ['white', '#ffffff']
  ].map(async ([variant, color]) => {
    const colored = artwork.replaceAll('currentColor', color)
    const data = await sharp(Buffer.from(colored), { density: 600 })
      .resize({ width })
      .png()
      .toBuffer()
    return [`site/public/brand/xnet-${name}-${variant}.png`, data]
  })
)

// Prepare every asset before replacing any existing file.
const outputs = await Promise.all([
  ...brandExports,
  ...rasterFiles.map(async ([path, kind, size, opaque]) => [path, await png(kind, size, opaque)]),
  Promise.resolve(['apps/web/public/favicon.svg', favicon]),
  Promise.resolve(['site/public/favicon.svg', favicon]),
  ico('desktop', [16, 24, 32, 48, 64, 128, 256]).then((data) => [
    'apps/electron/build/icon.ico',
    data
  ]),
  ico('favicon', [16, 24, 32, 48, 64, 128, 256]).then((data) => [
    'apps/web/public/favicon.ico',
    data
  ]),
  icns().then((data) => ['apps/electron/build/icon.icns', data])
])
await mkdir(file('site/public/brand'), { recursive: true })
await Promise.all(outputs.map(([path, data]) => writeFile(file(path), data)))
console.log(`Generated ${outputs.length} xNet icons and PNG exports`)
