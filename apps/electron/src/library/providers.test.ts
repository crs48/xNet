import { expect, it } from 'vitest'
import { chooseTrack, extractorUrl, parseCaptionBody, parseExtractorMetadata } from './providers'
import { imageContentType } from './service'

it('discovers real caption languages and prefers authored tracks within a language', () => {
  const parsed = parseExtractorMetadata({
    title: 'Full title',
    description: 'Full description',
    subtitles: { de: [{ ext: 'vtt', url: 'https://example.com/de.vtt' }] },
    automatic_captions: { en: [{ ext: 'json3', url: 'https://example.com/en.json3' }] }
  })
  expect(chooseTrack(parsed.tracks!, 'de')?.autoGenerated).toBe(false)
  expect(chooseTrack(parsed.tracks!, 'en')?.language).toBe('en')
  expect(chooseTrack(parsed.tracks!, 'fr')?.language).toBe('de')
})
it('retains full description text and records missing fields explicitly', () => {
  const description = 'a'.repeat(50000)
  expect(parseExtractorMetadata({ title: 'Title', description }).description).toBe(description)
  expect(parseExtractorMetadata({ title: 'Title' }).fields.description.state).toBe('unavailable')
})
it('rejects malformed caption bodies and timings instead of declaring no captions', () => {
  expect(() => parseCaptionBody('<html>Sign in</html>', 'json3')).toThrow()
  expect(() => parseCaptionBody('{}', 'json3')).toThrow()
  expect(() => parseCaptionBody('<html>Sign in</html>', 'vtt')).toThrow()
  expect(() => parseCaptionBody('WEBVTT\n\n00:01 --> bad\nPartial words', 'vtt')).toThrow(
    'not truncated'
  )
  expect(() =>
    parseCaptionBody(
      JSON.stringify({ events: [{ tStartMs: -1, segs: [{ utf8: 'words' }] }] }),
      'json3'
    )
  ).toThrow()
})
it('preserves JSON3 word fragments and VTT timing', () => {
  expect(
    parseCaptionBody(
      JSON.stringify({
        events: [
          { tStartMs: 2500, dDurationMs: 500, segs: [{ utf8: 'hel' }, { utf8: 'lo world' }] }
        ]
      }),
      'json3'
    )
  ).toEqual([{ startMs: 2500, durationMs: 500, text: 'hello world' }])
  expect(
    parseCaptionBody('WEBVTT\n\n00:01.000 --> 00:02.500\nHello &amp; welcome\n', 'vtt')
  ).toEqual([{ startMs: 1000, durationMs: 1500, text: 'Hello & welcome' }])
})
it('rejects local paths and provider identifiers that could change helper arguments', () => {
  expect(() =>
    extractorUrl({ platform: 'youtube', platformContentId: '--exec bad' } as never)
  ).toThrow()
  expect(() =>
    extractorUrl({ platform: 'generic', url: 'file:///private/example' } as never)
  ).toThrow()
})
it('resolves Instagram export fbids through the saved post URL without changing their identity', () => {
  for (const path of ['p/abc123', 'reel/abc123', 'creator/reel/abc123', 'tv/abc123']) {
    expect(
      extractorUrl({
        platform: 'instagram',
        platformContentId: '17866765571880000',
        url: `https://www.instagram.com/${path}/?utm_source=export`
      } as never)
    ).toBe('https://www.instagram.com/p/abc123/')
  }
  for (const url of [
    'https://evil.example/p/abc123/',
    'https://www.instagram.com/reels/audio/123/',
    'https://www.instagram.com/creator/'
  ]) {
    expect(() =>
      extractorUrl({ platform: 'instagram', platformContentId: '17866765571880000', url } as never)
    ).toThrow()
  }
})
it('does not accept HTML or SVG as a cached thumbnail', () => {
  expect(imageContentType(Buffer.from('<html>Login</html>'))).toBeNull()
  expect(imageContentType(Buffer.from('<svg/>'))).toBeNull()
  expect(imageContentType(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 0, 0]))).toBe('image/png')
})
