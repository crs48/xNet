export const LIBRARY_PROVIDER_VERSION = 'desktop-1/yt-dlp-2026.07.04'
export const CAPABILITIES = ['metadata', 'thumbnail', 'transcript', 'index'] as const
export type Capability = (typeof CAPABILITIES)[number]
export type WorkState =
  | 'queued'
  | 'running'
  | 'complete'
  | 'partial'
  | 'retry'
  | 'blocked'
  | 'unavailable'
  | 'not-applicable'
export type FieldCoverage = { state: 'complete' | 'unavailable' | 'partial'; reason?: string }
export type CaptionTrack = {
  url: string
  language: string
  format: 'json3' | 'vtt'
  autoGenerated: boolean
}
export type Cue = { startMs: number; durationMs: number; text: string }
export type LibraryMetadata = {
  title?: string
  description?: string
  author?: string
  thumbnailUrl?: string
  durationSeconds?: number
  language?: string
  tracks?: CaptionTrack[]
  fields: Record<string, FieldCoverage>
  provider: string
  fetchedAt: number
  evidence: unknown
}
export type LibraryResource = {
  id: string
  platform: string
  platformContentId: string
  url: string
  title: string
  sourceText: string
  actor: string
  privacy: string
  notes?: { id: string; title: string; text: string; url: string; author: string }[]
  metadata?: LibraryMetadata
  thumbnail?: { cid: string; contentType: string; bytes: number }
  transcript?: {
    cues: Cue[]
    language: string
    autoGenerated: boolean
    source: 'captions' | 'local-asr'
    fetchedAt: number
    provider: string
    evidence: string
  }
  addedAt: number
}
export type LibraryJob = {
  resourceId: string
  capability: Capability
  version: string
  language: string
  state: WorkState
  attempts: number
  nextAt: number
  reason: string | null
}
export type LibrarySearchResult = Omit<LibraryResource, 'metadata' | 'transcript'> & {
  metadata?: Omit<LibraryMetadata, 'evidence' | 'tracks'>
  snippet?: string
  startMs?: number
}
export type LibraryStatus = {
  paused: boolean
  resources: number
  counts: { capability: Capability; state: WorkState; count: number }[]
  recent: (LibraryJob & { title: string })[]
  providerVersion: string
}
