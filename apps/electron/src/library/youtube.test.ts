import { expect, it } from 'vitest'
import { parseYouTubePage } from './providers'

const page = (value: unknown) =>
  `<script>var ytInitialPlayerResponse = ${JSON.stringify(value)}; irrelevant();</script>`
const details = {
  videoId: 'abcdefghijk',
  title: 'A title with "quotes" and {braces}',
  shortDescription: 'Full text '.repeat(3000),
  author: 'Original author',
  lengthSeconds: '171',
  thumbnail: {
    thumbnails: [
      { url: 'https://i.ytimg.com/small.jpg', width: 120 },
      { url: 'https://i.ytimg.com/large.jpg', width: 1280 }
    ]
  }
}

it('reads full public metadata and caption tracks without evaluating scripts or needing a helper', () => {
  const result = parseYouTubePage(
    page({
      videoDetails: details,
      playabilityStatus: { status: 'OK' },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [
            {
              baseUrl: 'https://www.youtube.com/api/timedtext?v=abcdefghijk&sig=original',
              languageCode: 'de',
              kind: 'asr'
            }
          ]
        }
      }
    }),
    'abcdefghijk'
  )
  expect(result.title).toBe(details.title)
  expect(result.description).toBe(details.shortDescription)
  expect(result.thumbnailUrl).toBe('https://i.ytimg.com/large.jpg')
  expect(result.durationSeconds).toBe(171)
  expect(result.tracks?.[0]).toMatchObject({ language: 'de', autoGenerated: true, format: 'json3' })
  expect(new URL(result.tracks![0].url).searchParams.get('sig')).toBe('original')
  expect(new URL(result.tracks![0].url).searchParams.get('fmt')).toBe('json3')
})

it('distinguishes a known empty caption inventory from restricted playback', () => {
  const normal = parseYouTubePage(
    page({ videoDetails: details, playabilityStatus: { status: 'OK' } }),
    'abcdefghijk'
  )
  expect(normal.tracks).toEqual([])
  expect(normal.fields.captions.state).toBe('complete')
  const restricted = parseYouTubePage(
    page({
      videoDetails: details,
      playabilityStatus: { status: 'LOGIN_REQUIRED', reason: 'Sign in to confirm your age' }
    }),
    'abcdefghijk'
  )
  expect(restricted.title).toBe(details.title)
  expect(restricted.fields.captions).toEqual({
    state: 'partial',
    reason: 'Sign in to confirm your age'
  })
})

it('rejects wrong videos, deleted videos, malformed JSON, and truncated caption inventories', () => {
  expect(() => parseYouTubePage(page({ videoDetails: details }), 'differentID')).toThrow(
    'requested video'
  )
  expect(() =>
    parseYouTubePage(
      page({ playabilityStatus: { status: 'ERROR', reason: 'Video has been removed' } }),
      'abcdefghijk'
    )
  ).toThrow('removed')
  expect(() =>
    parseYouTubePage('<script>var ytInitialPlayerResponse = {broken};</script>', 'abcdefghijk')
  ).toThrow()
  expect(() =>
    parseYouTubePage(
      page({
        videoDetails: details,
        captions: { playerCaptionsTracklistRenderer: { captionTracks: [{ languageCode: 'en' }] } }
      }),
      'abcdefghijk'
    )
  ).toThrow('inventory')
  expect(() => parseYouTubePage('<html>Consent or login</html>', 'abcdefghijk')).toThrow(
    'did not return'
  )
})
