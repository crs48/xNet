import type { LibraryResource } from './types'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import Database from 'better-sqlite3'
import { beforeEach, afterEach, expect, it } from 'vitest'
import { LibraryStore } from './store'

let root: string
let path: string
let store: LibraryStore
const resource = (id = 'video-one'): LibraryResource => ({
  id,
  platform: 'youtube',
  platformContentId: 'abcdefghijk',
  title: 'A useful video',
  url: 'https://www.youtube.com/watch?v=abcdefghijk',
  sourceText: 'Original source notes',
  actor: 'Example',
  privacy: 'private',
  addedAt: 1
})
beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'xnet-library-'))
  path = join(root, 'library.db')
  store = new LibraryStore(path)
})
afterEach(async () => {
  store.close()
  await rm(root, { recursive: true, force: true })
})

it('deduplicates capability work and retains successful metadata across source scans', () => {
  store.seed(resource())
  const saved = {
    ...resource(),
    metadata: {
      title: 'Full fetched title',
      description: 'Full fetched text',
      fields: {},
      provider: 'fixture',
      fetchedAt: 2,
      evidence: {}
    }
  }
  store.put(saved)
  store.seed(resource())
  expect(store.status().counts.reduce((sum, row) => sum + row.count, 0)).toBe(4)
  expect(store.get('video-one')?.metadata?.description).toBe('Full fetched text')
})

it('recovers interrupted jobs and keeps future retries paused across restart', () => {
  store.seed(resource())
  const first = store.next(10)!
  expect(first.state).toBe('running')
  store.close()
  store = new LibraryStore(path)
  const replay = store.next(10)!
  expect(replay.capability).toBe(first.capability)
  store.finish(replay, 'retry', 'Network unavailable', 60_000)
  store.close()
  store = new LibraryStore(path)
  expect(
    store
      .status()
      .recent.some((job) => job.nextAt === 60_000 && job.reason === 'Network unavailable')
  ).toBe(true)
  expect(store.paused).toBe(true)
})

it('finds full descriptions and late transcript cues after restart', () => {
  const saved: LibraryResource = {
    ...resource(),
    metadata: {
      description: 'prefix '.repeat(5000) + 'rarewoodlandphrase',
      fields: {},
      provider: 'fixture',
      fetchedAt: 2,
      evidence: {}
    },
    transcript: {
      cues: [
        { startMs: 0, durationMs: 1000, text: 'opening '.repeat(4000) },
        { startMs: 7200000, durationMs: 1000, text: 'latecopperphrase' }
      ],
      language: 'de',
      autoGenerated: false,
      source: 'captions',
      fetchedAt: 2,
      provider: 'fixture',
      evidence: 'raw'
    }
  }
  store.seed(saved)
  store.index(saved)
  store.close()
  store = new LibraryStore(path)
  expect(store.search({ text: 'rarewoodlandphrase' })[0].id).toBe(saved.id)
  expect(store.search({ text: 'latecopperphrase' })[0].startMs).toBe(7200000)
  const card = store.search({ text: 'latecopperphrase' })[0]
  expect(card).not.toHaveProperty('transcript')
  expect(card.metadata).not.toHaveProperty('evidence')
  expect(card.metadata?.description?.length).toBeLessThanOrEqual(600)
  expect(store.get(saved.id)?.transcript?.cues).toHaveLength(2)
})

it('backfills a new provider version once without resetting completed current work', () => {
  store.seed(resource())
  store.close()
  const db = new Database(path)
  db.prepare("UPDATE work SET version='previous-provider',state='complete'").run()
  db.close()
  store = new LibraryStore(path)
  expect(store.status().counts.every((row) => row.state === 'queued' && row.count === 1)).toBe(true)
  const job = store.next(0, ['metadata'])!
  store.finish(job, 'complete')
  store.close()
  store = new LibraryStore(path)
  expect(store.next(0, ['metadata'])).toBeNull()
  expect(store.status().counts.find((row) => row.capability === 'metadata')?.state).toBe('complete')
  const check = new Database(path, { readonly: true })
  expect(
    check.prepare("SELECT COUNT(*) AS n FROM work WHERE version='previous-provider'").get()
  ).toEqual({ n: 4 })
  check.close()
})

it('does not consume retry attempts for user pauses or interrupted requests', () => {
  store.seed(resource())
  for (let i = 0; i < 10; i++) {
    const job = store.next(0, ['metadata'])!
    expect(job.attempts).toBe(1)
    store.finish(job, 'queued', 'Paused')
  }
  store.next(0, ['metadata'])
  store.close()
  store = new LibraryStore(path)
  expect(store.next(0, ['metadata'])?.attempts).toBe(1)
})

it('upgrades Instagram work without refetching completed YouTube metadata or losing backoff', () => {
  store.seed(resource('youtube'))
  store.seed({
    ...resource('instagram'),
    platform: 'instagram',
    url: 'https://www.instagram.com/p/abc123/'
  })
  // Both old providers had finished metadata; only Instagram needs the new pass.
  for (let i = 0; i < 2; i++) store.finish(store.next(0, ['metadata'])!, 'complete')
  store.pauseProvider('youtube', 60_000)
  store.setPaused(false)
  store.close()
  const db = new Database(path)
  db.prepare("UPDATE work SET version='desktop-2/youtube-page-1/yt-dlp-2026.07.04'").run()
  db.close()
  store = new LibraryStore(path)
  expect(store.next(0, ['metadata'])?.resourceId).toBe('instagram')
  expect(store.next(0, ['metadata'])).toBeNull()
  expect(store.next(0, ['thumbnail'])).toBeNull()
  expect(store.next(60_000, ['thumbnail'])?.resourceId).toBe('youtube')
  expect(store.paused).toBe(false)
  store.close()
  store = new LibraryStore(path)
  expect(store.next(0, ['metadata'])?.resourceId).toBe('instagram')
  expect(
    store.status().counts.find((row) => row.capability === 'metadata' && row.state === 'complete')
      ?.count
  ).toBe(1)
})

it('paginates every resource and safely handles FTS punctuation', () => {
  for (let i = 0; i < 85; i++) store.seed(resource(`source-${i}`))
  const ids = new Set(
    [0, 40, 80].flatMap((offset) => store.search({ offset }).map((row) => row.id))
  )
  expect(ids.size).toBe(85)
  expect(() => store.search({ text: '" ( OR *' })).not.toThrow()
})

it('returns bounded collection cards in request order without dropping missing or repeated items', () => {
  const saved = resource()
  saved.notes = [
    { id: 'note', title: 'Private note', text: 'Full body', url: '', author: 'fixture' }
  ]
  saved.transcript = {
    cues: [{ startMs: 0, durationMs: 1000, text: 'Full transcript' }],
    language: 'en',
    autoGenerated: false,
    source: 'captions',
    fetchedAt: 1,
    provider: 'fixture',
    evidence: 'Raw provider response'
  }
  store.seed(saved)
  const cards = store.cards([saved.id, 'missing-member', saved.id])
  expect(cards.map((card) => card?.id ?? null)).toEqual([saved.id, null, saved.id])
  expect(cards[0]).not.toHaveProperty('notes')
  expect(cards[0]).not.toHaveProperty('transcript')
  expect(store.cards([])).toEqual([])
  for (const invalid of [null, [''], [42], Array(101).fill(saved.id)])
    expect(() => store.cards(invalid)).toThrow('at most 100 valid resource IDs')
})

it('honors provider backoff while permitting local indexing', () => {
  store.seed(resource())
  store.pauseProvider('youtube', 60_000)
  const first = store.next(0)!
  expect(first.capability).toBe('index')
  store.finish(first, 'complete')
  expect(store.next(100)).toBeNull()
  expect(store.next(60_000)?.capability).toBe('metadata')
})

it('isolates capability pacing and never shortens a provider rate limit', () => {
  store.seed(resource())
  const metadata = store.next(0, ['metadata'])!
  store.finish(metadata, 'complete')
  store.pauseProvider('youtube:transcript', 120_000)
  expect(store.next(0, ['thumbnail'])?.capability).toBe('thumbnail')
  expect(store.next(0, ['transcript'])).toBeNull()
  store.pauseProvider('youtube', 180_000)
  store.pauseProvider('youtube', 60_000)
  store.retry()
  expect(store.next(120_000, ['transcript'])).toBeNull()
  expect(store.next(180_000, ['transcript'])?.capability).toBe('transcript')
})

it('requeues dependent gaps when metadata succeeds and resets explicit retry attempts', () => {
  store.seed(resource())
  const metadata = store.next(0, ['metadata'])!
  store.finish(metadata, 'blocked', 'Could not discover the video')
  const thumbnail = store.next(0, ['thumbnail'])!
  store.finish(thumbnail, 'unavailable', 'No metadata')
  const transcript = store.next(0, ['transcript'])!
  store.finish(transcript, 'blocked', 'No tracks')
  store.retry(resource().id)
  const retry = store.next(0, ['metadata'])!
  expect(retry.attempts).toBe(1)
  store.finish(retry, 'complete')
  expect(store.next(0, ['thumbnail'])?.state).toBe('running')
  expect(store.next(0, ['transcript'])?.state).toBe('running')
})

it('refuses future storage without changing its version', () => {
  store.close()
  const db = new Database(path)
  db.pragma('user_version=99')
  db.close()
  expect(() => new LibraryStore(path)).toThrow('preserved')
  const check = new Database(path, { readonly: true })
  expect(check.pragma('user_version', { simple: true })).toBe(99)
  check.close()
})

it('refuses a missing queue table instead of silently rebuilding it', () => {
  store.close()
  const db = new Database(path)
  db.exec('DROP TABLE attempts')
  db.close()
  expect(() => new LibraryStore(path)).toThrow('preserved')
})

it('indexes authored notes independently of fetched text and refreshes removed notes', () => {
  store.seed(resource())
  const notes = [
    {
      id: 'garden-note',
      title: 'Why I saved it',
      text: 'my personal copperbridge observation',
      url: 'https://example.com/note',
      author: 'fixture'
    }
  ]
  store.replaceSourceNotes(new Map([['video-one', notes]]))
  expect(store.search({ text: 'copperbridge' })[0].id).toBe('video-one')
  expect(store.search({ text: 'copperbridge' })[0]).not.toHaveProperty('notes')
  expect(store.get('video-one')?.notes).toEqual(notes)
  store.seed(resource())
  expect(store.get('video-one')?.notes).toEqual(notes)
  store.replaceSourceNotes(new Map())
  expect(store.search({ text: 'copperbridge' })).toEqual([])
})

