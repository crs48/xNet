import type { LibraryResource } from './types'
import { expect, it } from 'vitest'
import { parsePostPreview, parsePublicPage, parseTikTokPage } from './public-pages'
import { providerResource, queueProvider } from './source'

const resource = (url: string): LibraryResource => ({
  id: 'citation',
  url,
  platform: 'openai',
  platformContentId: url,
  title: url,
  sourceText: '',
  actor: '',
  privacy: 'private',
  addedAt: 1
})
const page = (item: unknown) =>
  `<script id="__UNIVERSAL_DATA_FOR_REHYDRATION__" type="application/json">${JSON.stringify({ __DEFAULT_SCOPE__: { 'webapp.video-detail': { itemInfo: { itemStruct: item } } } })}</script>`

it('routes archived citations through the URL provider without changing their source identity', () => {
  const input = resource('https://www.tiktokv.com/share/video/12345')
  expect(providerResource(input)).toMatchObject({
    id: 'citation',
    platform: 'tiktok',
    platformContentId: '12345',
    url: 'https://www.tiktok.com/@_/video/12345',
    privacy: 'private'
  })
  expect(input.platform).toBe('openai')
  expect(providerResource(resource('https://youtu.be/abcdefghijk?t=5')).platform).toBe('youtube')
  expect(providerResource(resource('https://github.com/owner/repo')).platform).toBe('github')
  expect(providerResource(resource('https://notyoutube.com/watch?v=abcdefghijk')).platform).toBe(
    'openai'
  )
})

it('reads full TikTok captions, source posters and native spoken tracks without executing scripts', () => {
  const result = parseTikTokPage(
    page({
      id: '12345',
      desc: 'A long written caption '.repeat(100),
      author: { uniqueId: 'creator' },
      textLanguage: 'en',
      video: {
        originCover: 'https://images.example/post.jpg',
        duration: 30,
        claInfo: {
          captionInfos: [
            {
              url: 'https://captions.example/post.vtt',
              languageCode: 'en',
              captionFormat: 'webvtt',
              isAutoGen: true
            }
          ]
        },
        subtitleInfos: [
          { Url: 'https://captions.example/post.vtt', LanguageCodeName: 'eng-US', Format: 'webvtt' }
        ]
      }
    }),
    '12345'
  )
  expect(result.description).toHaveLength(2300)
  expect(result.tracks).toEqual([
    { url: 'https://captions.example/post.vtt', language: 'en', format: 'vtt', autoGenerated: true }
  ])
  expect(result.thumbnailUrl).toContain('post.jpg')
  expect(result.fields.description.state).toBe('complete')
  expect(result.fields.title.state).toBe('partial')
})

it('keeps photo posts usable and refuses mismatched TikTok pages and malformed inventories', () => {
  const photo = {
    id: '12345',
    desc: 'Photos',
    imagePost: { images: [] },
    video: { cover: 'https://images.example/photo.jpg' }
  }
  expect(parseTikTokPage(page(photo), '12345').tracks).toEqual([])
  expect(() => parseTikTokPage(page(photo), '999')).toThrow('this post')
  expect(() => parseTikTokPage('<title>Log in</title>', '12345')).toThrow('public post data')
  expect(() => parseTikTokPage(page({ ...photo, video: { subtitleInfos: {} } }), '12345')).toThrow(
    'inventory'
  )
})

it('extracts an available web subtitle track and a rendered GitHub README', () => {
  const result = parsePublicPage(
    `<title>Repository &amp; notes</title><meta name="description" content="Preview"><meta property="og:image" content="/poster.jpg"><article class="markdown-body"><h1>Readme</h1><p>${'Late searchable text '.repeat(1000)}</p><script>not content</script></article><video><track kind="captions" srclang="fr" src="/subs.vtt"></video>`,
    'https://github.com/example/repo',
    true
  )
  expect(result.description?.length).toBeGreaterThan(19000)
  expect(result.description).not.toContain('not content')
  expect(result.fields.readme.state).toBe('complete')
  expect(result.tracks?.[0]).toEqual({
    url: 'https://github.com/subs.vtt',
    language: 'fr',
    format: 'vtt',
    autoGenerated: false
  })
  expect(result.thumbnailUrl).toBe('https://github.com/poster.jpg')
})

it('labels Reddit previews as partial and never treats them as transcripts', () => {
  const result = parsePostPreview({ title: 'A saved comment', author_name: 'creator' }, 'reddit')
  expect(result.fields.description.state).toBe('partial')
  expect(result.fields.captions.state).toBe('unavailable')
  expect(() => parsePostPreview({ error: 'not found' }, 'reddit')).toThrow('no public post')
})

it('keeps unrelated web hosts independent of the archive that imported them', () => {
  expect(queueProvider(resource('https://example.org/a'))).toBe('web:example.org')
  expect(queueProvider(resource('https://www.example.org/b'))).toBe('web:example.org')
  expect(queueProvider(resource('https://another.org/a'))).toBe('web:another.org')
})

it('reads GitHub embedded READMEs and repository facts without retaining viewer data', () => {
  const data = {
    payload: {
      csrf_tokens: { secret: 'must-not-retain' },
      codeViewRepoRoute: {
        overview: {
          overviewFiles: [
            { preferredFileType: 'license', richText: '<p>License text</p>' },
            {
              preferredFileType: 'readme',
              path: 'README.md',
              richText: '<article><h1>Example</h1><p>Searchable readme body</p></article>'
            }
          ]
        }
      },
      sidebarAbout: {
        description: 'Repository purpose',
        topics: [{ name: 'learning' }, { name: 'graphs' }],
        website: 'https://example.org',
        stargazerCount: 123,
        forksCount: 4,
        repo: { license: { spdxId: 'MIT' } },
        viewer: { secret: 'must-not-retain' }
      }
    }
  }
  const result = parsePublicPage(
    `<title>Example repository</title><script data-target="react-app.embeddedData" type="application/json">${JSON.stringify(data)}</script>`,
    'https://github.com/example/repo',
    true
  )
  expect(result.description).toContain('Repository purpose')
  expect(result.description).toContain('Searchable readme body')
  expect(result.description).toContain('learning, graphs')
  expect(result.fields.readme.state).toBe('complete')
  expect(result.fields.description.state).toBe('complete')
  expect(result.evidence).toMatchObject({
    repository: { stars: 123, forks: 4, license: 'MIT', readmePath: 'README.md' }
  })
  expect(JSON.stringify(result)).not.toContain('must-not-retain')
  expect(result.description).not.toContain('License text')
})

it('indexes visible article text without claiming hidden content was retrieved', () => {
  const result = parsePublicPage(
    '<title>Essay</title><nav>Navigation</nav><article><p>Late searchable passage</p><script>secret script</script></article>',
    'https://example.org/essay'
  )
  expect(result.description).toBe('Late searchable passage')
  expect(result.fields.description.state).toBe('partial')
})
