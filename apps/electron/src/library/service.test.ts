it('honors a rate limit after retry and restart, then processes every remaining video', async () => {
  for (let i = 0; i < 250; i++) service.store.seed(resource(`video-${i}`))
  stubs.metadata.mockRejectedValueOnce(
    new LibraryProviderError('HTTP 429', 'retry', Date.now() + 60_000, 'provider')
  )
  service.resume()
  await vi.advanceTimersByTimeAsync(2000)
  service.retry()
  await service.close()
  service = open(root)
  service.resume()
  await vi.advanceTimersByTimeAsync(30_000)
  expect(stubs.metadata).toHaveBeenCalledOnce()
  expect(service.status().nextAt).toBeGreaterThan(Date.now())
  await vi.advanceTimersByTimeAsync(300_000)
  expect(count('metadata', 'complete')).toBe(250)
  expect(count('metadata', 'queued')).toBe(0)
  expect(count('metadata', 'retry')).toBe(0)
  expect(service.status().running).toEqual([])
  expect(service.status().nextAt).toBeNull()
  for (let i = 0; i < 250; i++)
    expect(service.store.get(`video-${i}`)?.metadata?.title).toBe('Fetched title')
})

